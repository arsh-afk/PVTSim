"""Data quality report generation for time series."""

from __future__ import annotations

from pathlib import Path
from typing import Any, Dict

import pandas as pd


def write_quality_report(
    name: str,
    df: pd.DataFrame,
    meta: Dict[str, Any],
    output_dir: Path,
) -> Path:
    """Write a data quality report for a time series.

    Per P1-2: Report only. Never repair.
    """
    report_path = output_dir / f"{name}.md"

    lines = [
        f"# Data Quality Report: {name}",
        "",
        f"**Source:** {name}.csv",
        f"**Generated:** Auto-generated by AquaSolar Living",
        "",
        "## Summary",
        "",
        f"- **Rows:** {len(df)}",
    ]

    # Time span
    if "timestamp" in df.columns:
        ts_col = df["timestamp"]
        lines.append(f"- **Start:** {ts_col.min()}")
        lines.append(f"- **End:** {ts_col.max()}")

        # Interval regularity
        if len(ts_col) > 1:
            diffs = ts_col.diff().dropna()
            median_interval = diffs.median()
            lines.append(f"- **Median interval:** {median_interval}")

    # Gap analysis
    gaps = []
    if "timestamp" in df.columns:
        ts_col = df["timestamp"]
        expected_interval = meta.get("interval")
        if expected_interval:
            # Find gaps
            diffs = ts_col.diff()
            gap_threshold = pd.Timedelta(expected_interval) * 1.5
            gaps = diffs[diffs > gap_threshold]
            lines.append(f"- **Gaps detected:** {len(gaps)}")
            for idx, gap in gaps.head(5).items():
                lines.append(f"  - {idx} to {df.loc[idx, 'timestamp']}: {gap}")

    # QC code counts
    qc_col = "qc_flag"
    if qc_col in df.columns:
        qc_counts = df[qc_col].value_counts()
        lines.append(f"- **QC code distribution:**")
        for code, count in qc_counts.items():
            lines.append(f"  - {code}: {count}")

    # Flat-lined segments
    numeric_cols = df.select_dtypes(include=["number"]).columns
    for col in numeric_cols:
        # Find consecutive identical values
        diff = df[col].diff().abs()
        flat_runs = (diff == 0).astype(int).cumsum()
        # Count runs of length > 1
        lines.append(f"- **Column '{col}' flat segments:** {len(diff[diff == 0])} values")

    # Values outside valid_range
    valid_range = meta.get("valid_range")
    if valid_range:
        for col, bounds in valid_range.items():
            if col in df.columns:
                low = bounds.get("min")
                high = bounds.get("max")
                if low is not None:
                    below = (df[col] < low).sum()
                    if below > 0:
                        lines.append(f"- **{col} below min ({low}):** {below} values")
                if high is not None:
                    above = (df[col] > high).sum()
                    if above > 0:
                        lines.append(f"- **{col} above max ({high}):** {above} values")

    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("Report generated automatically. Data was NOT modified.")

    report_path.write_text("\n".join(lines), encoding="utf-8")
    return report_path
